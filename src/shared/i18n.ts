type Locale =
  | 'en'
  | 'zh-CN'
  | 'zh-TW'
  | 'ja'
  | 'ko'
  | 'es'
  | 'fr'
  | 'de'
  | 'ru'
  | 'pt-BR'
  | 'it'
  | 'tr'
  | 'vi'
  | 'th'
  | 'id'
  | 'ar'
  | 'hi'
  | 'pl';

const messagesByLocale: Record<Locale, Messages> = {
  en,
  'zh-CN': zhCN,
  'zh-TW': zhTW,
  ja,
  ko,
  es,
  fr,
  de,
  ru,
  'pt-BR': ptBR,
  it,
  tr,
  vi,
  th,
  id,
  ar,
  hi,
  pl,
};

const getBrowserLocale = (): Locale => {
  const fallback: Locale = 'en';
  const lang =
    (globalThis as typeof globalThis & { navigator?: Navigator }).navigator?.language?.toLowerCase() ??
    'en';

  if (lang.startsWith('zh-tw') || lang.startsWith('zh-hk') || lang.startsWith('zh-hant')) {
    return 'zh-TW';
  }
  if (lang.startsWith('zh')) {
    return 'zh-CN';
  }
  if (lang.startsWith('pt')) {
    return 'pt-BR';
  }
  if (lang.startsWith('ja')) {
    return 'ja';
  }
  if (lang.startsWith('ko')) {
    return 'ko';
  }
  if (lang.startsWith('es')) {
    return 'es';
  }
  if (lang.startsWith('fr')) {
    return 'fr';
  }
  if (lang.startsWith('de')) {
    return 'de';
  }
  if (lang.startsWith('ru')) {
    return 'ru';
  }
  if (lang.startsWith('it')) {
    return 'it';
  }
  if (lang.startsWith('tr')) {
    return 'tr';
  }
  if (lang.startsWith('vi')) {
    return 'vi';
  }
  if (lang.startsWith('th')) {
    return 'th';
  }
  if (lang.startsWith('id')) {
    return 'id';
  }
  if (lang.startsWith('ar')) {
    return 'ar';
  }
  if (lang.startsWith('hi')) {
    return 'hi';
  }
  if (lang.startsWith('pl')) {
    return 'pl';
  }
  if (lang.startsWith('en')) {
    return 'en';
  }
  return fallback;
};

export const t = (key: keyof typeof en): string => {
  const locale = getBrowserLocale();
  const messages = messagesByLocale[locale] ?? en;
  return messages[key] ?? en[key] ?? key;
};
